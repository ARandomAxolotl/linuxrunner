#!/usr/bin/env python3
"""Embed the guest vDSO as a C array: embed.py libvdso.so.elf vdso_blob.c PAGES

A generated source (instead of .incbin) gives the build a real dependency on the
vDSO contents, so rebuilding the vDSO always rebuilds what embeds it. An empty
placeholder (no aarch64 toolchain) embeds zero pages, as .incbin did.
"""
import sys
data = open(sys.argv[1], 'rb').read()
size = int(sys.argv[3]) * 4096
if len(data) > size:
    sys.exit(f'vDSO is {len(data)} bytes; VDSO_PAGES allows {size}')
body = ','.join(str(b) for b in data) or '0'
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by vdso/arm64/embed.py from %s (%d bytes). Do not edit.\n' % (sys.argv[1].split('/')[-1], len(data)))
    f.write('#include "kernel/vdso.h"\n')
    f.write('__attribute__((aligned(4096))) const char vdso_data[VDSO_PAGES * (1 << 12)] = {%s};\n' % body)
